/* ============================================================================
   analytics.js — the Google Analytics tag, shared by both pages
   ----------------------------------------------------------------------------
   The tag used to be inline in index.html only. guide.html is generated by
   build-guide.js, so it never had one, and the reference page — half of what
   this site is — was invisible in the reports. One copy here, loaded by both.

   Nothing is sent unless the page is being served from the published site. A
   file:// session or a local server is development, not an audience, and
   should not turn up in the numbers.
   ========================================================================== */

(function () {
  "use strict";

  const ID = "G-K73PMH1KCZ";

  const host = location.hostname;
  const local =
    location.protocol === "file:" ||
    host === "" ||
    host === "localhost" ||
    host === "[::1]" ||
    host.endsWith(".local") ||
    /^(127\.|0\.0\.0\.0|192\.168\.|10\.)/.test(host);
  if (local) return;

  const s = document.createElement("script");
  s.async = true;
  s.src = "https://www.googletagmanager.com/gtag/js?id=" + ID;
  document.head.appendChild(s);

  window.dataLayer = window.dataLayer || [];
  window.gtag = function () {
    window.dataLayer.push(arguments);
  };
  gtag("js", new Date());
  gtag("config", ID);
})();
